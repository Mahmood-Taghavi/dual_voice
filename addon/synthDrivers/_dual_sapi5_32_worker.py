# NVDA 2026.2 keeps the 32-bit copy of the SAPI5 implementation in
# <NVDA application directory>/_synthDrivers32, not in the small frozen
# synthDriverHost runtime's own synthDrivers package.
# The 32-bit host first prepends our add-on synthDrivers folder; we also
# append NVDA's 32-bit driver folder for its _sapi5 / _sonic modules.
_NVDA_32BIT_DRIVERS = os.path.join(globalVars.appDir, "_synthDrivers32")
if not os.path.isdir(_NVDA_32BIT_DRIVERS):
    raise ImportError(
        "Dual Voice 32-bit cannot find NVDA's 32-bit drivers directory: "
        + _NVDA_32BIT_DRIVERS
    )
if _NVDA_32BIT_DRIVERS not in synthDrivers.__path__:
    synthDrivers.__path__.append(_NVDA_32BIT_DRIVERS)

# CRITICAL: import the 32-bit *bootstrap* wrapper, not _sapi5 directly.
# NVDA ships _synthDrivers32/sapi5.py alongside _sapi5.py and _sonic.py.
# The wrapper first registers the 32-bit SpeechLib COM type library in
# sys.modules["comInterfaces.SpeechLib"] and switches _sonic.SONIC_DLL_PATH
# to the 32-bit sonic.dll. Only then does it load ._sapi5.SynthDriver.
# Directly importing synthDrivers._sapi5 skips both required initializations
# and fails with "No module named 'comInterfaces.SpeechLib'".
_BOOTSTRAP_32 = os.path.join(_NVDA_32BIT_DRIVERS, "sapi5.py")
if not os.path.isfile(_BOOTSTRAP_32):
    raise ImportError(
        "Dual Voice 32-bit cannot find NVDA's SAPI5 bootstrap wrapper: "
        + _BOOTSTRAP_32
    )
BaseSapi5 = importlib.import_module("synthDrivers.sapi5").SynthDriver

