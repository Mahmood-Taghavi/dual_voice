def escape(text):
    """Escape SAPI XML text without depending on xml.sax (not in 32-bit NVDA host).

    Ampersands must be replaced first so generated entities are not re-escaped.
    """
    return (text.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;"))


def quoteattr(value):
    """Return a safely quoted XML attribute including its quotation marks.

    This is a small local equivalent of xml.sax.saxutils.quoteattr. It also
    encodes line breaks and tabs, which must not be normalized in attributes.
    """
    value = (escape(str(value))
             .replace("\n", "&#10;")
             .replace("\r", "&#13;")
             .replace("\t", "&#9;"))
    if '"' not in value:
        return '"' + value + '"'
    if "'" not in value:
        return "'" + value + "'"
    return '"' + value.replace('"', '&quot;') + '"'


# Must match dual_sapi5_32.py in the main process.
_SETTINGS_PREFIX = "\x00DUAL_VOICE_32_SETTINGS_V1:"

_DEFAULT_PREFS = {
    "secondVoice": "",
    "secondRate": 50,
    "secondPitch": 50,
    "secondVolume": 100,
    "secondIsLatin": False,
    "nonLatinPriority": False,
    "considerContext": False,
    "firstVolume": 100,
}


class _SafeSapiXml(str):
    """Keep *our already escaped and generated* XML intact in base SAPI5.

    Never wrap arbitrary input in this type. The worker first escapes user
    text and quote-escapes voice token attributes.
    """
    def replace(self, old, new, count=-1):
        if old == "<" and new == "&lt;":
            return self
        return super().replace(old, new, count)


def _percent(value, default):
    try:
        return max(0, min(100, int(value)))
    except (ValueError, TypeError, OverflowError):
        return default


def _decode_preferences(payload):
    prefs = _DEFAULT_PREFS.copy()
    if not isinstance(payload, dict):
        return prefs
    prefs["secondVoice"] = str(payload.get("secondVoice") or "")
    for key, default in (
        ("secondRate", 50),
        ("secondPitch", 50),
        ("secondVolume", 100),
        ("firstVolume", 100),
    ):
        prefs[key] = _percent(payload.get(key, default), default)
    for key in ("secondIsLatin", "nonLatinPriority", "considerContext"):
        prefs[key] = bool(payload.get(key, False))
    return prefs


def _choose_markers(text):
    """Pick four private-use characters which do not occur in the source.

    These markers delimit tags produced by the ORIGINAL _dualvoice.nlp
    algorithm, allowing the spoken text to be escaped *after* segmentation.
    """
    chars = []
    for cp in range(0xE000, 0xF900):
        ch = chr(cp)
        if ch not in text:
            chars.append(ch)
            if len(chars) == 4:
                return chars
    raise ValueError("No available XML segmentation markers")


def _render_dual_voice_xml(text, prefs, primaryXmlName, knownXmlNames):
    secondary = prefs["secondVoice"]
    if secondary not in knownXmlNames:
        # The saved secondary voice might belong to the 64-bit driver.
        # Never ask the 32-bit SAPI runtime to switch to a missing voice.
        secondary = primaryXmlName
    firstVolume = prefs["firstVolume"]
    secondaryVolume = prefs["secondVolume"]
    secondaryRate = round((prefs["secondRate"] - 50) / 5)
    secondaryPitch = round((prefs["secondPitch"] - 50) / 5)

    # All generated attributes must be XML-quoted, including SAPI Name values.
    secondOpen = (
        "<voice required=" + quoteattr("Name=" + secondary) + ">"
        + '<volume level="%d">' % secondaryVolume
        + '<rate absspeed="%d">' % secondaryRate
        + '<pitch absmiddle="%d">' % secondaryPitch
    )
    secondClose = "</pitch></rate></volume></voice>"
    firstOpen = '<volume level="%d">' % firstVolume
    firstClose = "</volume>"

    # _dualvoice.nlp selects Latin vs. non-Latin spans. We preserve its exact
    # decisions and replace generated tag sentinels AFTER escaping text spans.
    nonLatinOpen, nonLatinClose, latinOpen, latinClose = _choose_markers(text)
    latinPriority = not prefs["nonLatinPriority"]
    marked = _dualvoice.nlp(
        text,
        latinPriority,
        prefs["considerContext"],
        nonLatinOpen,
        nonLatinClose,
        latinOpen,
        latinClose,
    )
    if prefs["secondIsLatin"]:
        markersToXml = {
            latinOpen: secondOpen,
            latinClose: secondClose,
            nonLatinOpen: firstOpen,
            nonLatinClose: firstClose,
        }
    else:
        markersToXml = {
            latinOpen: firstOpen,
            latinClose: firstClose,
            nonLatinOpen: secondOpen,
            nonLatinClose: secondClose,
        }
    parts = re.split("([" + re.escape("".join(markersToXml)) + "])", marked)
    return "".join(markersToXml[p] if p in markersToXml else escape(p) for p in parts)


class SynthDriver(BaseSapi5):
    # The host imports this name. It is not selectable on the main-process list.
    name = "_dual_sapi5_32_worker"
    description = "Dual Voice SAPI5 worker (32-bit)"
    # The remote proxy does not expose an accessor for 'useWasapi'; keep NVDA
    # 2026.2's WASAPI implementation enabled internally, not as a UI setting.
    supportedSettings = tuple(s for s in BaseSapi5.supportedSettings if s.id != "useWasapi")

    def __init__(self):
        super().__init__()
        self._dualVoicePrefs = _DEFAULT_PREFS.copy()
        self._dualVoiceXmlNamesCache = None

    def _getAvailableVariants(self):
        """Expose per-voice XML Name attributes over the existing variants RPC.

        These are metadata only, not user-selectable speech variants. They are
        consumed by dual_sapi5_32._getAvailableVoices() in the main process.
        """
        if self._dualVoiceXmlNamesCache is not None:
            return self._dualVoiceXmlNamesCache
        result = OrderedDict()
        tokens = self._getVoiceTokens()
        # Match NVDA's indexed enumeration: some SAPI IEnumVARIANT objects
        # returned by direct iteration do not expose the right interface.
        for i in range(len(tokens)):
            try:
                token = tokens[i]
                voiceID = token.Id
                try:
                    xmlName = token.GetAttribute("Name")
                except Exception:
                    xmlName = token.GetDescription()
                result[voiceID] = VoiceInfo(voiceID, xmlName or token.GetDescription(), None)
            except Exception:
                log.warning("Dual Voice 32: skipping unreadable voice token", exc_info=True)
        self._dualVoiceXmlNamesCache = result
        return result

    def speak(self, speechSequence):
        speechSequence = list(speechSequence)
        if speechSequence and isinstance(speechSequence[0], str) and speechSequence[0].startswith(_SETTINGS_PREFIX):
            raw = speechSequence.pop(0)[len(_SETTINGS_PREFIX):]
            try:
                self._dualVoicePrefs = _decode_preferences(json.loads(raw))
            except (ValueError, TypeError):
                log.warning("Dual Voice 32: invalid settings packet", exc_info=True)
                self._dualVoicePrefs = _DEFAULT_PREFS.copy()

        voiceAttrs = self._getAvailableVariants()
        idToXmlName = {key: voice.displayName for key, voice in voiceAttrs.items()}
        primaryXmlName = idToXmlName.get(self.voice)
        if not primaryXmlName:
            # A basic SAPI voice should have a Name attribute, but never
            # generate an invalid required="Name=..." if that isn't the case.
            primaryXmlName = self.tts.Voice.GetDescription()
        knownXmlNames = set(idToXmlName.values())

        transformed = []
        for item in speechSequence:
            if isinstance(item, str):
                transformed.append(_SafeSapiXml(_render_dual_voice_xml(
                    item,
                    self._dualVoicePrefs,
                    primaryXmlName,
                    knownXmlNames,
                )))
            else:
                transformed.append(item)
        # NVDA's base SAPI5 handles bookmarks, language/rate commands, Sonic,
        # WASAPI audio, speech completion, cancel, and pause.
        return super().speak(transformed)
